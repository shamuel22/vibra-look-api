#!/usr/bin/env node
/**
 * Copies the app's pure domain model (types, shades, constraint rules, recipe helpers) into
 * `src/contracts/domain/` so the API and the app share one source of truth.
 *
 *   pnpm contracts:sync            # copy from ../src/domain (the app repo)
 *   pnpm contracts:check           # fail if the copy is stale (skips when the app is absent)
 *   APP_DOMAIN_DIR=/path pnpm …    # other location of the app's src/domain
 *
 * The only transformation is adding `.js` to relative imports (NodeNext resolution).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const FILES = ['types.ts', 'shades.ts', 'constraints.ts', 'recipe.ts'];
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.env.APP_DOMAIN_DIR ?? join(root, '..', 'src', 'domain'));
const target = join(root, 'src', 'contracts', 'domain');
const check = process.argv.includes('--check');

const HEADER = '// GENERATED by scripts/sync-contracts.mjs from the app repo (src/domain). Do not edit here.\n';

function transform(code) {
  return HEADER + code.replace(/(from\s+'\.\/[\w-]+)(')/g, '$1.js$2');
}

if (!existsSync(source)) {
  if (check) {
    console.log(`contracts: app domain not found at ${source}; skipping check`);
    process.exit(0);
  }
  console.error(`contracts: app domain not found at ${source} (set APP_DOMAIN_DIR)`);
  process.exit(1);
}

let stale = 0;
for (const file of FILES) {
  const next = transform(readFileSync(join(source, file), 'utf8'));
  const dest = join(target, file);
  const current = existsSync(dest) ? readFileSync(dest, 'utf8') : '';
  if (current === next) continue;
  stale++;
  if (check) console.error(`contracts: ${file} differs from the app`);
  else writeFileSync(dest, next);
}

if (check && stale) {
  console.error('contracts: run `pnpm contracts:sync` and commit the result');
  process.exit(1);
}
console.log(check ? 'contracts: in sync' : `contracts: ${stale} file(s) updated`);
